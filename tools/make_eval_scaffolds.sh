#!/usr/bin/env bash
# Regenerate evals/<case>/{fixture.sh,case.yaml} from evals/_fixtures/config-generic.sh.
# The eval harness gives each scaffold HOME = the run's temporary home, so the fixture lands where the skills look.
# Cases named *not-installed* / *not-configured* get the stage's keys cleared (they already are in the generic config
# for tomodrgn/teamtomo/chimerax; warp/relion/m cases clear WARP/RELION explicitly).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; FIX="$ROOT/evals/_fixtures/config-generic.sh"
for d in "$ROOT"/evals/*/; do
  c="$(basename "$d")"; [[ $c == _* || $c == results ]] && continue; [ -f "$d/prompt.md" ] || continue
  clear=""
  case "$c" in
    warptools-preprocess-warp-not-installed|m-refine-not-installed) clear="WARP_ENV_SCRIPT" ;;
    relion-refine-relion-not-installed) clear="RELION_ENV_SCRIPT" ;;
  esac
  {
    echo '#!/usr/bin/env bash'
    echo '# GENERATED by tools/make_eval_scaffolds.sh -- edit evals/_fixtures/config-generic.sh instead'
    echo 'set -e; mkdir -p "$HOME/.config/cryoet-skills"'
    echo "cat > \"\$HOME/.config/cryoet-skills/config.sh\" <<'CFG'"
    if [ -n "$clear" ]; then
      sed -e "s/^$clear=.*/$clear=\"\"/" -e "1s/.*/# Generic fixture config for plugin evals (this case: $clear cleared = not installed)./" "$FIX"
    else cat "$FIX"; fi
    echo 'CFG'
  } > "$d/fixture.sh"
  chmod +x "$d/fixture.sh"
  printf 'schema_version: "1.1"\nname: %s\ncontext:\n  scaffold_script: fixture.sh\n' "$c" > "$d/case.yaml"
done
echo "scaffolds written for $(ls -d "$ROOT"/evals/*/case.yaml 2>/dev/null | wc -l) cases"
